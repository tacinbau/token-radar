import {readFileSync,writeFileSync,mkdirSync,cpSync,existsSync,readdirSync,rmSync} from 'node:fs';
import {resolve,join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {buildBoard} from './lib/model.ts';
import {buildDossier} from './vendor/makefun-board.ts';
const args=process.argv.slice(2), at=args.indexOf('--input');
if(at>=0&&!args[at+1]) throw new Error('--input requires a path');
const input=at>=0?args[at+1]:'/input/snapshot.json';
const out=resolve(process.env.MAKEFUN_OUTPUT_DIR||'./out');
const root=dirname(fileURLToPath(import.meta.url));
const board=buildBoard(JSON.parse(readFileSync(input,'utf8')));
mkdirSync(out,{recursive:true});
const json=JSON.stringify(board,null,2)+'\n';
writeFileSync(join(out,'board.json'),json);
writeFileSync(join(out,'data.js'),'window.TOKEN_RADAR = '+json.trimEnd().replace(/</g,'\\u003c')+';\n');
for(const dir of ['dashboard','screenshots']) if(existsSync(join(root,dir))) cpSync(join(root,dir),join(out,dir),{recursive:true});
const shots=join(out,'screenshots');
if(existsSync(shots)&&readdirSync(shots).some(n=>/\.(png|jpe?g)$/i.test(n))) writeFileSync(join(out,'dossier.json'),buildDossier(out,{text_max_bytes:65536}));
else {rmSync(join(out,'dossier.json'),{force:true});console.warn('Warning: no screenshots yet; dossier generation skipped.');}
console.log(`Built ${board.rows.length} protocols in ${out}`);
