  function openDetail(slug) {
    state.selected = slug;
    writeHash();
    render();
    var d = document.getElementById('detail');
    if (d && d.scrollIntoView) d.scrollIntoView({ block: 'start' });
  }

  function render() {
    app.textContent = '';
    var shell = el('div', { class: 'shell' });
    shell.appendChild(header());
    shell.appendChild(lede());
    shell.appendChild(controls());
    if (state.selected) {
      var detail = detailPanel();
      if (detail) shell.appendChild(detail);
    }
    shell.appendChild(state.tab === 'pre-token' ? boardTable() : liveTable());
    if (state.tab === 'pre-token') shell.appendChild(modelPanel());
    shell.appendChild(el('footer', { class: 'foot', text: 'Token Radar, model ' + DATA.model_version + '. Snapshot ' + DATA.as_of + ', DefiLlama protocol index, ' + DATA.rows.length + ' pre-token protocols ranked. Implied value is a model of what a launch would be worth, not a prediction that one happens.' }));
    app.appendChild(shell);
    app.setAttribute('aria-busy', 'false');
  }

  readHash();
  render();
  window.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && state.selected) { state.selected = null; writeHash(); render(); }
  });
